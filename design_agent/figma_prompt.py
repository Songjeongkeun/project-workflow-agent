"""
Figma 프롬프트 생성
"""
from schemas import ScreenPlan

def build_figma_prompt(screen_plan: ScreenPlan, figma_url: str) -> str:
    """
    화면 계획(screen_plan.json)을 기반으로
    Codex에 전달할 Figma 작업 프롬프트 생성
    Codex가 수행해야 할 화면 생성, 수정 및 검증 규칙을 구성
    """
    plan_json = screen_plan.model_dump_json(indent=2)

    prompt = f"""
    당신은 Figma UI 디자인 전문가입니다. 
    당신은 Codex와 연결된 Figma MCP를 사용해
    지정된 Figma 파일에 실제 프레임을 생성해야 합니다.
    설명만 하지 말고 실제로 Figma MCP 도구를 사용하세요.
    아래 화면 계획을 바탕으로 Figma Design에 편집 가능한 UI 프레임을 생성하세요.

    [작업 대상 Figma]
    {figma_url}

    [화면 계획]
    {plan_json}

    [필수 작업 규칙]
    1. Figma MCP 연결과 대상 파일의 쓰기 권한을 확인합니다.
    2. 지정된 Figma 파일과 페이지에서만 작업합니다.
    3. 작업 대상 screen_id에 해당하는 기존 프레임은 화면 계획과 일치하도록 수정할 수 있습니다. 작업 대상과 관계없는 프레임 및 레이어는 수정하거나 삭제하지 않습니다.
    4. 각 screen_id마다 편집 가능한 프레임을 생성합니다.
    5. 프레임 이름은 'SCR-001 예약 상세'처럼 작성합니다.
    6. elements, states, next_screens를 반영합니다.
    7. 텍스트와 UI 요소는 편집 가능한 레이어로 생성합니다.
    8. 실제 생성한 프레임의 URL과 노드 ID를 반환합니다.
    9. 도구 실행에 실패하면 성공했다고 보고하지 않습니다.
    10. 화면마다 필요한 UI 요소를 그룹화하여 편집 가능한 Figma 레이어로 구성합니다.
    11. 오류 및 예외 상태는 기본 화면과 구분하여 표현합니다. 필요하면 상태별 변형 프레임을 생성합니다.
    12. 기존에 동일한 screen_id의 프레임이 존재하면 중복 생성하지 않고 해당 프레임을 재사용합니다. 화면 계획과 비교하여 누락된 요소가 있다면 기존 프레임을 수정하고 다시 검증합니다.
    13. Figma MCP 작업 이후 실제 생성된 프레임을 조회하여 화면 ID, 필수 요소, 노드 ID를 확인합니다.
    14. next_screens는 화면 간 이동 관계를 나타냅니다. 프로토타입 연결을 지원하는 경우 연결하고, 지원하지 않으면 미구현 사항으로 보고합니다.
    15. Figma MCP에서 실제 확인한 URL과 노드 ID만 반환합니다. 확인할 수 없는 값은 임의로 생성하지 않습니다.    
    16. 모든 화면 생성 작업이 끝나면 Figma MCP를 사용하여 실제 프레임과 레이어를 다시 조회합니다.
    17. 화면 계획과 Figma 결과를 screen_id별로 비교합니다.
        - screen_id: 해당 프레임이 실제 존재하는지 확인
        - elements: type, label에 해당하는 UI 요소가 존재하는지 확인
        - states: 기본 상태와 예외 상태가 표현되었는지 확인
        - next_screens: 화면 간 이동 관계가 반영되었는지 확인
    18. elements의 state를 고려하여 UI 요소를 확인합니다.
        예를 들어 '신청 저장 실패' 상태의 '다시 시도' 버튼은 해당 오류 상태에서 확인해야 합니다.
    19. states는 별도 프레임, 컴포넌트 변형 또는 상태별 레이어로 표현할 수 있습니다. 반드시 별도 프레임일 필요는 없습니다.
    20. next_screens는 다른 화면으로 이동하는 경우에만 프로토타입 연결 여부를 확인합니다.
        API 호출이나 현재 화면에서 수행하는 동작은 Figma 프로토타입 연결과 구분합니다.
    21. 필수 UI 요소가 누락되었거나 확인할 수 없는 경우에는 검증에 성공한 것으로 판단하지 않습니다.
        확인되지 않은 항목을 error에 구체적으로 작성합니다.
    22. 화면 계획에 정의되지 않은 기능을 임의로 추가하지 않습니다.
    23. 모든 필수 화면, UI 요소, 상태를 확인하고 확인 가능한 필수 화면 이동까지 검증한 경우에만 status를 "success"로 반환합니다.
    24. 검증에 실패하거나 확인되지 않은 필수 항목이 있으면 status를 "failed"로 반환하고, error에 화면 ID와 누락 또는 미확인 항목을 기록합니다.
    25. 실제 Figma MCP 조회 결과를 근거로 검증합니다.
        Figma MCP를 호출하지 못했다면 성공으로 보고하지 않습니다.
    26. screen_plan의 supported_platforms를 확인하여 대상 플랫폼에 적합한 UI 디자인을 생성합니다.
        - 웹: 데스크톱 웹 레이아웃을 기본으로 설계합니다.
        - 모바일 앱: 모바일 화면 크기와 터치 UI를 고려합니다.
        - 웹과 모바일 모두 포함된 경우: 플랫폼별 레이아웃을 구분합니다.
        - 플랫폼 정보가 불명확하거나 누락된 경우: 
            - 화면 계획의 기능, UI 요소, 사용자 흐름을 분석하여 가장 적합한 플랫폼을 추론하고 디자인을 생성합니다.
            - 이 경우에도 화면 생성 작업을 중단하지 않습니다.      
            - 추론한 플랫폼을 기준으로 일관된 화면을 생성하며, 기존 결과 JSON 구조는 변경하지 않습니다.

    [기존 Figma 화면 처리 규칙]
    1. Figma 파일에서 screen_id에 해당하는 프레임을 먼저 조회합니다.
    2. 해당 프레임이 존재하지 않으면 새로 생성합니다.
    3. 해당 프레임이 이미 존재하면 중복 생성하지 않고, 현재 screen_plan.json과 비교합니다.
    4. 기존 화면에서 필수 UI 요소, 화면 상태, 안내 문구, 화면 이동 관계가 누락되거나 잘못된 경우 Figma MCP에서 지원하는 수정 도구를 사용하여 해당 프레임을 요구사항과 일치시킵니다.
        기존 프레임을 직접 수정할 수 없다면 수정이 불가능한 구체적인 이유를 error에 기록합니다. 실제 수정하지 않았는데 수정했다고 보고해서는 안 됩니다.
    5. 기존 화면의 정상적인 요소는 최대한 유지하고 누락되거나 잘못된 부분만 수정합니다.
    6. 작업 대상 screen_id와 관계없는 다른 프레임과 레이어는 수정하거나 삭제하지 않습니다.
    7. 화면을 생성하거나 수정한 뒤 Figma MCP로 다시 조회하여 필수 요소와 상태가 반영되었는지 확인합니다.
    8. 생성 또는 수정 권한이 없다면 성공으로 보고하지 않고 권한 오류와 미완료 항목을 명시합니다.
    9. 모든 화면의 생성 및 검증이 완료된 경우에만 status를 success로 반환합니다.

    [출력 규칙]
    - 최종 결과는 JSON 객체로 반환합니다.
    - 설명문이나 Markdown 표는 출력하지 않습니다.
    - screens에는 screen_plan의 각 screen_id를 한 번씩 포함합니다.
    - 상태별 프레임이 여러 개라면 기본 화면의 URL과 노드 ID를 반환합니다.
    - 이미 생성된 프레임이 있으면 중복 생성하지 않고 조회하여 재사용합니다.
    - 실제 Figma MCP에서 확인한 값만 반환합니다.
    - 모든 화면을 확인했을 때만 status를 success로 설정합니다.
    - 작업이 완료되지 않았다면 status를 failed로 설정하고 error에 이유를 작성합니다.

    [결과 구조]
    {{
        "status": "success",
        "error": "",
        "screens": [
            {{
                "screen_id": "SCR-001",
                "figma_url": "실제 Figma 프레임 URL",
                "node_id": "실제 노드 ID"
            }}
        ]
    }}

    """
    return prompt